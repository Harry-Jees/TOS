# char -> tuple of 7 five-char row strings
GLYPHS: dict[str, tuple[str, ...]] = {
    ch: tuple(rows.split("/")) for ch, rows in _RAW.items()
}

MISSING = ("#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####")
# a few characters that look better drawn from the missing-box base
GLYPH_REPLACEMENTS = {
    "\u00b0": ("..##.", ".#..#", "..##.", ".....", ".....", ".....", "....."),
    "\u2022": (".....", ".##..", ".##..", ".....", ".....", ".....", "....."),
}


def glyph(ch: str) -> tuple[str, ...]:
    if ch in GLYPHS:
        return GLYPHS[ch]
    return GLYPH_REPLACEMENTS.get(ch, MISSING)


def text_width(text: str, scale: int = 1) -> int:
    return len(text) * CELL_W * scale


def text_height(lines: int = 1, scale: int = 1) -> int:
    return lines * CELL_H * scale


def wrap(text: str, max_chars: int) -> list[str]:
    """Word-wrap for the virtual screen; never splits words unless forced."""
    if max_chars <= 0:
        return [text]
    out: list[str] = []
    for para in text.split("\n"):
        line = ""
        for word in para.split(" "):
            while len(word) > max_chars:
                if line:
                    out.append(line)
                    line = ""
                out.append(word[:max_chars])
                word = word[max_chars:]
            if not line:
                line = word
            elif len(line) + 1 + len(word) <= max_chars:
                line += " " + word
            else:
                out.append(line)
                line = word
        out.append(line)
    return out
